/**
 * @file Database.hpp
 * @brief The SQLite persistence layer used by JDN Bank.
 */
#pragma once

#include "Types.hpp"
#include <cstdint>
#include <string>

struct sqlite3;

namespace jdn {

/**
 * @brief Owns one SQLite connection and provides the database operations used
 * by the service layer.
 *
 * Database uses the RAII pattern: the constructor opens the connection and
 * the destructor closes it automatically. Copying is disabled because two
 * objects must not accidentally pretend to own the same SQLite handle.
 */
class Database {
public:
    explicit Database(const std::string& path);
    ~Database();

    Database(const Database&) = delete;
    Database& operator=(const Database&) = delete;

    /** @brief Create missing tables and apply small schema upgrades. */
    void migrate();

    /** @brief Execute SQL that does not need returned rows. */
    void exec(const std::string& sql) const;

    /** @brief Execute a query and return each result row as a Row. */
    Rows query(const std::string& sql) const;

    /** @brief Read one integer result, or fallback when it is unavailable. */
    std::int64_t scalarInt(const std::string& sql,
                           std::int64_t fallback = 0) const;

    /** @brief Read one text result, or fallback when it is unavailable. */
    std::string scalarText(const std::string& sql,
                           const std::string& fallback = "") const;

    /** @brief Return the row id generated by the most recent INSERT. */
    std::int64_t lastInsertId() const;

    /** @brief Start an immediate SQLite transaction. */
    void begin();

    /** @brief Commit the current SQLite transaction. */
    void commit();

    /** @brief Roll back the current transaction without throwing. */
    void rollback() noexcept;

    /**
     * @brief Quote a value for use as a SQLite string literal.
     *
     * This is retained for the existing SQL-building design. New database
     * code should prefer prepared statements when the project grows further.
     */
    static std::string quote(const std::string& value);

private:
    sqlite3* handle_{};
};

/**
 * @brief RAII helper that rolls a transaction back unless commit() is called.
 *
 * This is an example of object lifetime being used to make error handling
 * safer: an exception cannot accidentally leave the transaction open.
 */
class Transaction {
public:
    explicit Transaction(Database& db);
    ~Transaction();

    /** @brief Commit the transaction and mark it as completed. */
    void commit();

private:
    Database& db_;
    bool committed_{false};
};

} // namespace jdn

